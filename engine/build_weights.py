#!/usr/bin/env python3
"""Generate engine/weights.py from the knowledge table.

Symptom points combine FREQUENCY with SPECIFICITY. Frequency alone is
misleading: hepatomegaly is ~90% frequent in Gaucher, but it is also frequent in
Niemann-Pick, Pompe and MPS I, so observing it barely moves the differential.
What matters diagnostically is how much more likely the finding is in this
disease than in the others -- a likelihood ratio.

    points = base(frequency) * specificity

    specificity = p(symptom | this disease) / mean p(symptom | any disease)
                  clipped to [0.35, 2.0]

So vertical supranuclear gaze palsy (near-unique to NPC) keeps its full weight,
while hepatomegaly is discounted to roughly a third.
"""
import csv, json, os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.environ.get("LSD_DATA", os.path.join(HERE, "..", "data"))
OUT = os.path.join(HERE, "weights.py")

DISEASES = ["gaucher", "fabry", "pompe", "mps1", "niemann_pick_c", "krabbe"]

# Category ceilings from the spec (Section 4.2).
CEILINGS = {"enzyme": 40, "genetic": 35, "symptom": 30, "biomarker": 15, "vitals": 10}


def base_points(p):
    """Frequency band -> raw points, before specificity weighting."""
    if p >= 0.995: return 8.0
    if p >= 0.80:  return 6.0
    if p >= 0.30:  return 4.0
    if p >= 0.05:  return 2.0
    return 1.0


def main():
    all_rows = [r for r in csv.DictReader(open(f"{DATA}/knowledge_table.csv"))
                if r["category"] == "symptom"]
    rows = [r for r in all_rows if r["probability"]]

    # p(symptom | disease). A symptom listed for a disease but with no recorded
    # frequency still counts as an association when judging specificity --
    # treating it as absent would make shared findings look discriminating.
    UNKNOWN_FREQ = 0.40
    BACKGROUND = 0.02
    prob, assoc = defaultdict(dict), defaultdict(dict)
    for r in all_rows:
        if r["probability"]:
            p = float(r["probability"])
            prob[r["hpo_id"]][r["disease"]] = p
            assoc[r["hpo_id"]][r["disease"]] = p
        else:
            assoc[r["hpo_id"]][r["disease"]] = UNKNOWN_FREQ

    labels = {r["hpo_id"]: r["symptom"] for r in all_rows}

    symptom_weights = defaultdict(dict)
    specificity = {}
    for hpo, per_disease in prob.items():
        # Share of this symptom's total probability mass that belongs to this
        # disease. A finding unique to one disease takes nearly all the mass; a
        # finding common to all six takes about a sixth of it.
        total = sum(assoc[hpo].get(d, BACKGROUND) for d in DISEASES)
        for disease, p in per_disease.items():
            share = p / total if total > 0 else 1.0 / len(DISEASES)
            # share ~0.90 (unique) -> ~2.0 ; share ~0.167 (ubiquitous) -> ~0.37
            spec = max(0.35, min(2.0, share * 2.2))
            specificity[(hpo, disease)] = round(spec, 3)
            pts = base_points(p) * spec
            symptom_weights[disease][hpo] = round(pts, 2)

    # Normalise each disease's symptom track so a full house hits the ceiling.
    # Normalise so a realistic presentation reaches the ceiling. Real patients
    # present with 3-6 recorded findings, not twelve: normalising to the top 12
    # meant the textbook Gaucher triad (splenomegaly, hepatomegaly, anaemia,
    # thrombocytopenia) could never exceed ~5.6 of 30 symptom points.
    TYPICAL_FINDINGS = 5
    scale = {}
    for d in DISEASES:
        top = sorted(symptom_weights[d].values(), reverse=True)[:TYPICAL_FINDINGS]
        total = sum(top) or 1.0
        scale[d] = round(CEILINGS["symptom"] / total, 4)

    with open(OUT, "w") as fh:
        fh.write('"""AUTO-GENERATED by build_weights.py. Do not edit by hand.\n\n')
        fh.write("Every number here traces to a published source:\n")
        fh.write("  symptom frequencies : HPO phenotype.hpoa v2026-09-02\n")
        fh.write("                        (includes 4,357 Orphanet annotations)\n")
        fh.write("  enzyme thresholds   : Italy NBS IJNS 10:00003; Missouri IJNS 11:00048\n")
        fh.write("  biomarker cutoffs   : lyso-Gb1 IJMS 23:01627; lyso-Gb3 IJMS 24:03223\n")
        fh.write("  NP-C symptom weights: Suspicion Index, Neurology 2012\n")
        fh.write("  prevalence priors   : Illinois / NY / Italy newborn screening\n")
        fh.write('"""\n\n')
        fh.write(f"DISEASES = {json.dumps(DISEASES, indent=4)}\n\n")
        fh.write(f"CATEGORY_CEILINGS = {json.dumps(CEILINGS, indent=4)}\n\n")
        fh.write("# disease -> HPO id -> points (frequency x specificity)\n")
        fh.write("SYMPTOM_POINTS = ")
        fh.write(json.dumps({d: symptom_weights[d] for d in DISEASES}, indent=1))
        fh.write("\n\n# disease -> scaling factor so a full presentation hits the ceiling\n")
        fh.write(f"SYMPTOM_SCALE = {json.dumps(scale, indent=4)}\n\n")
        fh.write("# HPO id -> human-readable label\n")
        fh.write("SYMPTOM_LABELS = ")
        fh.write(json.dumps(labels, indent=1))
        fh.write("\n")

    # report
    print(f"{'disease':<18}{'symptoms':>9}{'scale':>8}   most specific finding")
    for d in DISEASES:
        best = max(symptom_weights[d].items(), key=lambda kv: kv[1])
        print(f"{d:<18}{len(symptom_weights[d]):>9}{scale[d]:>8.3f}   "
              f"{labels[best[0]][:40]} ({best[1]})")

    print("\nspecificity check -- shared findings should be discounted,")
    print("near-unique hallmark findings should keep full weight:")
    for hpo in ["HP:0002240", "HP:0001744", "HP:0000511", "HP:0001014",
                "HP:0007957", "HP:0001903"]:
        if hpo in prob:
            ds = ", ".join(f"{d}={specificity[(hpo,d)]:.2f}" for d in prob[hpo])
            n = len(assoc[hpo])
            print(f"  {labels[hpo][:34]:<36} (in {n} dis.)  {ds}")
    print(f"\n-> {OUT}")


if __name__ == "__main__":
    main()
